import { AISafetyAnalysis } from "./types";

export function buildCrisisMessage(safety: AISafetyAnalysis): string {
  if (safety.isIntrusiveThought) {
    return `Слышу, как пугает эта мысль. Нежелательная мысль сама по себе не доказывает, что ты собираешься действовать. Мне важно уточнить: есть ли у тебя прямо сейчас намерение или конкретный план причинить вред себе или кому-то? Если опасность непосредственная, позвони в 112 (Казахстан) или попроси находящегося рядом человека помочь.`;
  }

  return `Слышу, как тяжело тебе сейчас. Если ты можешь причинить вред себе или кому-то прямо сейчас, позвони в экстренную службу 112 (Казахстан) или попроси находящегося рядом человека помочь. Ты также можешь запросить живого человека в СИНО.`;
}

export function buildSafeFallback(safety: AISafetyAnalysis): string {
  if (safety.isIntrusiveThought) {
    return `Понимаю, что эта мысль может пугать. Нежелательная мысль сама по себе не доказывает, что ты собираешься действовать, и я не буду делать вывод о тебе по одной мысли. Что в ней тревожит тебя сильнее всего?`;
  }

  if (safety.isParanoiaOrDelusion) {
    return `Понимаю, что это ощущение тревожит. Я не могу подтвердить, что угроза реальна, и не хочу выдавать предположение за факт. Ты сейчас в непосредственной опасности или тебе прежде всего страшно из-за этой мысли?`;
  }

  if (safety.isReassuranceLoop) {
    return `Понимаю, как хочется получить полную уверенность. Я не могу дать гарантию или продолжать бесконечные проверки, но могу остаться рядом с тем, что ты чувствуешь сейчас.`;
  }

  return `Похоже, сейчас я не могу подключиться к помощнику. Твоё сообщение сохранено — попробуй отправить его ещё раз чуть позже.`;
}

